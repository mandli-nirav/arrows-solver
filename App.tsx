import React, {useCallback, useEffect, useMemo, useState} from 'react';
import {
  AppState,
  BackHandler,
  ColorValue,
  Platform,
  PlatformColor,
  Pressable,
  ScrollView,
  StatusBar,
  StyleSheet,
  Text,
  useColorScheme,
  View,
} from 'react-native';
import {SafeAreaProvider, SafeAreaView} from 'react-native-safe-area-context';
import Svg, {Path} from 'react-native-svg';
import NativeSolver from './specs/NativeSolver';
import {ICONS, IconName} from './src/icons';

/**
 * Material 3 colour roles. On Android 12+ they come from the phone's Dynamic Color (Material You) tonal palettes,
 * generated by the system from the wallpaper (system_accent1/2, system_neutral1/2), mapped to roles as in the
 * Material 3 spec. Older phones get a fixed scheme from the same seed as the game's accent (#5B71FF).
 */
type Scheme = Record<
  | 'primary' | 'onPrimary' | 'primaryContainer' | 'onPrimaryContainer' | 'secondaryContainer' | 'onSecondaryContainer'
  | 'surface' | 'surfaceContainer' | 'surfaceContainerHigh' | 'onSurface' | 'onSurfaceVariant' | 'outline' | 'error',
  ColorValue
>;

const sys = (n: string) => PlatformColor(`@android:color/${n}`);

function scheme(dark: boolean): Scheme {
  if (Platform.OS === 'android' && Number(Platform.Version) >= 31) {
    return dark
      ? {
          primary: sys('system_accent1_200'), onPrimary: sys('system_accent1_800'),
          primaryContainer: sys('system_accent1_700'), onPrimaryContainer: sys('system_accent1_100'),
          secondaryContainer: sys('system_accent2_700'), onSecondaryContainer: sys('system_accent2_100'),
          surface: sys('system_neutral1_900'), surfaceContainer: sys('system_neutral1_800'),
          surfaceContainerHigh: sys('system_neutral2_800'), onSurface: sys('system_neutral1_100'),
          onSurfaceVariant: sys('system_neutral2_200'), outline: sys('system_neutral2_400'), error: '#F2B8B5',
        }
      : {
          primary: sys('system_accent1_600'), onPrimary: sys('system_accent1_0'),
          primaryContainer: sys('system_accent1_100'), onPrimaryContainer: sys('system_accent1_900'),
          secondaryContainer: sys('system_accent2_100'), onSecondaryContainer: sys('system_accent2_900'),
          surface: sys('system_neutral1_10'), surfaceContainer: sys('system_neutral1_50'),
          surfaceContainerHigh: sys('system_neutral2_50'), onSurface: sys('system_neutral1_900'),
          onSurfaceVariant: sys('system_neutral2_700'), outline: sys('system_neutral2_500'), error: '#B3261E',
        };
  }
  return dark
    ? {
        primary: '#BAC3FF', onPrimary: '#0E2A99', primaryContainer: '#2B42B0', onPrimaryContainer: '#DEE0FF',
        secondaryContainer: '#424659', onSecondaryContainer: '#DFE1F9', surface: '#131318', surfaceContainer: '#1F1F25',
        surfaceContainerHigh: '#2A2930', onSurface: '#E4E1E9', onSurfaceVariant: '#C6C5D0', outline: '#90909A', error: '#F2B8B5',
      }
    : {
        primary: '#4A5CC8', onPrimary: '#FFFFFF', primaryContainer: '#DEE0FF', onPrimaryContainer: '#00105C',
        secondaryContainer: '#DFE1F9', onSecondaryContainer: '#171B2C', surface: '#FBF8FF', surfaceContainer: '#EFEDF4',
        surfaceContainerHigh: '#E9E7EF', onSurface: '#1B1B21', onSurfaceVariant: '#46464F', outline: '#767680', error: '#B3261E',
      };
}

/** Official Material Symbols (filled), see src/icons.ts. */
function Icon({name, color, size = 24}: {name: IconName; color: ColorValue; size?: number}) {
  const i = ICONS[name];
  return (
    <Svg width={size} height={size} viewBox={i.viewBox}>
      {i.d.map((d, k) => (
        <Path key={k} d={d} fill={color as string} />
      ))}
    </Svg>
  );
}

type Mode = 'system' | 'light' | 'dark';

export default function App() {
  const systemDark = useColorScheme() === 'dark';
  const [mode, setModeState] = useState<Mode>(() => (NativeSolver.getThemeMode() as Mode) || 'system');
  const dark = mode === 'dark' || (mode === 'system' && systemDark);
  const [screen, setScreen] = useState<'home' | 'settings'>('home');
  const setMode = (m: Mode) => {
    setModeState(m);
    NativeSolver.setThemeMode(m); // the drawer over the game follows the same choice
  };

  useEffect(() => {
    const sub = BackHandler.addEventListener('hardwareBackPress', () => {
      if (screen === 'settings') {
        setScreen('home');
        return true;
      }
      return false;
    });
    return () => sub.remove();
  }, [screen]);
  const c = useMemo(() => scheme(dark), [dark]);
  const s = useMemo(() => styles(c), [c]);
  const [enabled, setEnabled] = useState(false);
  const [status, setStatus] = useState('');
  const [gameMissing, setGameMissing] = useState(false);

  const refresh = useCallback(() => {
    setEnabled(NativeSolver.isServiceEnabled());
    setStatus(NativeSolver.getStatus());
  }, []);

  useEffect(() => {
    refresh();
    const sub = AppState.addEventListener('change', st => st === 'active' && refresh());
    const t = setInterval(refresh, 1500);
    return () => {
      sub.remove();
      clearInterval(t);
    };
  }, [refresh]);

  const isError = status.startsWith('⚠');
  const statusText = status.replace(/^⚠\s*/, '') || 'Idle';

  const Item = ({icon, title, sub, onPress, trailing}: {icon: IconName; title: string; sub?: string; onPress?: () => void; trailing?: React.ReactNode}) => (
    <Pressable
      accessibilityRole={onPress ? 'button' : 'text'}
      accessibilityLabel={sub ? `${title}. ${sub}` : title}
      onPress={onPress}
      disabled={!onPress}
      android_ripple={onPress ? {color: c.secondaryContainer} : undefined}
      style={s.item}>
      <Icon name={icon} color={c.onSurfaceVariant} />
      <View style={s.itemText}>
        <Text style={s.itemTitle}>{title}</Text>
        {sub ? <Text style={s.itemSub}>{sub}</Text> : null}
      </View>
      {trailing}
    </Pressable>
  );

  const Switch = ({on}: {on: boolean}) => (
    <View style={[s.track, on ? s.trackOn : s.trackOff]}>
      <View style={[s.thumb, on ? s.thumbOn : s.thumbOff]} />
    </View>
  );

  const steps: [IconName, string][] = [
    ['touch_app', 'Start a level, then tap the accessibility button. The drawer slides down from the top.'],
    ['troubleshoot', 'Analyze reads the level. Green arrows can leave now, orange ones are blocked.'],
    ['play_arrow', 'Solve clears it one arrow at a time and stops if anything looks wrong.'],
    ['map', 'Analyze also zooms out and centres the board. Map shows the whole level.'],
  ];

  const IconButton = ({icon, label, onPress}: {icon: IconName; label: string; onPress: () => void}) => (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={label}
      onPress={onPress}
      android_ripple={{color: c.secondaryContainer, borderless: true, radius: 24}}
      style={s.iconButton}>
      <Icon name={icon} color={c.onSurfaceVariant} />
    </Pressable>
  );

  const modes: [Mode, IconName, string, string][] = [
    ['system', 'brightness_auto', 'System', 'Follow the phone'],
    ['light', 'light_mode', 'Light', 'Always light'],
    ['dark', 'dark_mode', 'Dark', 'Always dark'],
  ];

  if (screen === 'settings') {
    return (
      <SafeAreaProvider>
        <StatusBar barStyle={dark ? 'light-content' : 'dark-content'} />
        <SafeAreaView style={s.root}>
          <View style={s.appBar}>
            <IconButton icon="arrow_back" label="Back" onPress={() => setScreen('home')} />
            <Text style={s.appBarTitle}>Settings</Text>
          </View>
          <ScrollView contentContainerStyle={s.content}>
            <Text style={s.groupLabel}>Appearance</Text>
            <View style={s.card} accessibilityRole="radiogroup">
              {modes.map(([m, icon, title, sub]) => {
                const on = mode === m;
                return (
                  <Pressable
                    key={m}
                    accessibilityRole="radio"
                    accessibilityState={{checked: on}}
                    accessibilityLabel={`${title}. ${sub}`}
                    onPress={() => setMode(m)}
                    android_ripple={{color: c.secondaryContainer}}
                    style={s.item}>
                    <Icon name={icon} color={on ? c.primary : c.onSurfaceVariant} />
                    <View style={s.itemText}>
                      <Text style={s.itemTitle}>{title}</Text>
                      <Text style={s.itemSub}>{sub}</Text>
                    </View>
                    <View style={[s.radio, on && s.radioOn]}>{on ? <View style={s.radioDot} /> : null}</View>
                  </Pressable>
                );
              })}
            </View>
            <View style={s.note}>
              <Icon name="palette" color={c.onSurfaceVariant} size={20} />
              <Text style={s.noteText}>Colours come from your wallpaper (Material You). The drawer over the game uses the same appearance.</Text>
            </View>
          </ScrollView>
        </SafeAreaView>
      </SafeAreaProvider>
    );
  }

  return (
    <SafeAreaProvider>
      <StatusBar barStyle={dark ? 'light-content' : 'dark-content'} />
      <SafeAreaView style={s.root}>
        <View style={[s.appBar, s.appBarEnd]}>
          <IconButton icon="settings" label="Settings" onPress={() => setScreen('settings')} />
        </View>
        <ScrollView contentContainerStyle={s.content}>
          <View style={s.header}>
            <View style={s.badge}>
              <Icon name="arrow_outward" color={c.onPrimaryContainer} size={28} />
            </View>
            <Text style={s.title}>Arrows Solver</Text>
            <Text style={s.lead}>A Material You drawer over the Arrows game, opened with the accessibility button.</Text>
          </View>

          <View style={s.card}>
            <Item
              icon="settings_accessibility"
              title="Solver service"
              sub={enabled ? 'On' : 'Turn it and its shortcut on in Accessibility'}
              onPress={() => NativeSolver.openAccessibilitySettings()}
              trailing={<Switch on={enabled} />}
            />
            <Item
              icon="admin_panel_settings"
              title="Allow restricted settings"
              sub="Only if the service switch is greyed out"
              onPress={() => NativeSolver.openAppInfo()}
              trailing={<Icon name="chevron_right" color={c.onSurfaceVariant} />}
            />
          </View>

          <Pressable
            accessibilityRole="button"
            onPress={() => setGameMissing(!NativeSolver.openGame())}
            android_ripple={{color: c.primaryContainer}}
            style={s.fab}>
            <Icon name="sports_esports" color={c.onPrimary} size={20} />
            <Text style={s.fabText}>Open Arrows</Text>
          </Pressable>
          {gameMissing ? <Text style={s.error}>Arrows (com.ecffri.arrows) is not installed.</Text> : null}

          <View style={s.card}>
            <Text style={s.cardTitle}>How to use</Text>
            {steps.map(([icon, text]) => (
              <View key={icon} style={s.step}>
                <View style={s.stepIcon}>
                  <Icon name={icon} color={c.onSecondaryContainer} size={20} />
                </View>
                <Text style={s.stepText}>{text}</Text>
              </View>
            ))}
          </View>

          <View style={s.card}>
            <Item
              icon={isError ? 'error' : status.startsWith('Solved') ? 'check_circle' : 'info'}
              title="Status"
              sub={statusText}
            />
            <Item
              icon="lock"
              title="Nothing is kept"
              sub="Levels, screenshots and progress are never saved. Only errors are written to errors.log for fixing later."
            />
          </View>
        </ScrollView>
      </SafeAreaView>
    </SafeAreaProvider>
  );
}

